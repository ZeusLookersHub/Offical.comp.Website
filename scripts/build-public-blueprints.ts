/**
 * Writes core/mission-engine/public-blueprints.generated.ts: the browser's copy of the
 * blueprints, with the role, the four strategy layers, the worked examples, the gates and
 * the per-tool notes removed. That is the prompt engineering itself, and it never leaves
 * the server. Run: npm run build:public-blueprints
 */
import { writeFileSync } from 'node:fs';
import { blueprints } from '../core/mission-engine/registry.ts';
import { leaksPrivateData, stripPrivate } from '../core/mission-engine/public.ts';

export const publicShape = () => blueprints.map(stripPrivate);

if (process.argv.includes('build-public-blueprints')) {
  const shape = publicShape();
  const leaks = shape.flatMap(bp => leaksPrivateData(bp).map(f => `${bp.id}.${f}`));
  if (leaks.length) { console.error('private data left in the public copy:', leaks.join(', ')); process.exit(1); }
  writeFileSync('core/mission-engine/public-blueprints.generated.ts',
    '// GENERATED by scripts/build-public-blueprints.ts — do not edit.\n'
    + '// The browser\'s copy: labels, questions, options and extraction patterns only.\n'
    + 'import type { Blueprint } from \'./types.ts\';\n\n'
    + 'export const publicBlueprints = ' + JSON.stringify(shape) + ' as unknown as readonly Blueprint[];\n');
  console.log('written', shape.length, 'blueprints');
}
